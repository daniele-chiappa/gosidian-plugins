export const CATALOG: Record<Lang, Record<Key, string>> = { it, en };
export type MessageKey = Key;

// pickLang reads a language tag: it-IT is it, en-GB is en, anything else
// the fallback.
export function pickLang(tag: string | null | undefined, fallback: Lang = 'it'): Lang {
  const base = (tag ?? '').trim().toLowerCase().split(/[-_]/)[0];
  return base === 'it' || base === 'en' ? base : fallback;
}

export function t(lang: Lang, key: Key, params: Record<string, string | number> = {}): string {
  const text = CATALOG[lang][key] ?? CATALOG.it[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (m, name: string) => (name in params ? String(params[name]) : m));
}

function locale(lang: Lang): string {
  return lang === 'it' ? 'it-IT' : 'en-US';
}

// money is an amount in dollars, as the server counts it: two decimals,
// and what rounds to nothing but is not nothing says so.
export function money(lang: Lang, usd: number): string {
  const f = new Intl.NumberFormat(locale(lang), {
    style: 'currency', currency: 'USD', currencyDisplay: 'narrowSymbol', minimumFractionDigits: 2, maximumFractionDigits: 2,
  });
  if (usd > 0 && usd < 0.005) {
    return '< ' + f.format(0.01);
  }
  return f.format(usd);
}

// amount is a count in the short form: 3076168 tokens is 3,1 Mln or 3.1M.
export function amount(lang: Lang, n: number): string {
  return new Intl.NumberFormat(locale(lang), { notation: 'compact', maximumFractionDigits: 1 }).format(n);
}

export function integer(lang: Lang, n: number): string {
  return new Intl.NumberFormat(locale(lang), { maximumFractionDigits: 0 }).format(n);
}

export function clock(lang: Lang, iso: string): string {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) {
    return '';
  }
  return new Intl.DateTimeFormat(locale(lang), { hour: '2-digit', minute: '2-digit' }).format(d);
}
